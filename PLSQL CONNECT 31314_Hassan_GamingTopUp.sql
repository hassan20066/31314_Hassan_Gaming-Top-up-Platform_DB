CREATE OR REPLACE PROCEDURE Process_TopUp (
    p_player_id IN NUMBER,
    p_item_id IN NUMBER
) AS
    v_wallet_balance NUMBER;
    v_item_price NUMBER;
BEGIN
    SELECT wallet_balance
    INTO v_wallet_balance
    FROM Players
    WHERE player_id = p_player_id;

    SELECT price
    INTO v_item_price
    FROM TopUp_Items
    WHERE item_id = p_item_id;

    IF v_wallet_balance >= v_item_price THEN
        UPDATE Players
        SET wallet_balance = wallet_balance - v_item_price
        WHERE player_id = p_player_id;

        INSERT INTO Orders (player_id, item_id, status)
        VALUES (p_player_id, p_item_id, 'Completed');

        DBMS_OUTPUT.PUT_LINE('Top-up successful! Wallet updated.');
        COMMIT;
    ELSE
        INSERT INTO Orders (player_id, item_id, status)
        VALUES (p_player_id, p_item_id, 'Failed');

        DBMS_OUTPUT.PUT_LINE('Top-up failed: Insufficient balance.');
        COMMIT;
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Error: Player ID or Item ID does not exist.');
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('An unexpected error occurred.');
END;
