CREATE OR REPLACE PACKAGE BODY Gaming_TopUp_Pkg AS

    FUNCTION Is_System_Blocked RETURN BOOLEAN IS
        v_holiday_count INT;
        v_day_name VARCHAR2(20);
    BEGIN
        v_day_name := TO_CHAR(SYSDATE, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH');

        IF v_day_name IN ('SAT', 'SUN') THEN
            RETURN TRUE;
        END IF;

        SELECT COUNT(*)
        INTO v_holiday_count
        FROM Public_Holidays
        WHERE TRUNC(holiday_date) = TRUNC(SYSDATE);

        IF v_holiday_count > 0 THEN
            RETURN TRUE;
        END IF;

        RETURN FALSE;
    END Is_System_Blocked;

    PROCEDURE Process_Player_TopUp (
        p_tx_id IN INT,
        p_player_id IN INT,
        p_game_id IN INT,
        p_amount IN NUMBER
    ) IS
    BEGIN
        IF Is_System_Blocked() THEN
            RAISE_APPLICATION_ERROR(-20003, 'System Lock: Cannot process transactions during weekends or holidays.');
        ELSE
            INSERT INTO Transactions (tx_id, player_id, game_id, amount, status)
            VALUES (p_tx_id, p_player_id, p_game_id, p_amount, 'Completed');

            COMMIT;

            DBMS_OUTPUT.PUT_LINE('Transaction ' || p_tx_id || ' processed successfully via Package.');
        END IF;

    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            DBMS_OUTPUT.PUT_LINE('Transaction Failed in Package: ' || SQLERRM);
    END Process_Player_TopUp;

END Gaming_TopUp_Pkg;
