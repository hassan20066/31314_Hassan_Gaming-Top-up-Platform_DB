CREATE OR REPLACE TRIGGER Secure_Players_Trigger
BEFORE INSERT OR UPDATE OR DELETE ON Players
FOR EACH ROW
DECLARE
    v_holiday_count NUMBER;
    v_day_name VARCHAR2(20);
BEGIN
    v_day_name := TO_CHAR(SYSDATE, 'DAY');

    SELECT COUNT(*)
    INTO v_holiday_count
    FROM Public_Holidays
    WHERE TRUNC(holiday_date) = TRUNC(SYSDATE);

    IF TRIM(v_day_name) IN ('SATURDAY', 'SUNDAY') OR v_holiday_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'DML operations are restricted during weekends and public holidays for security.');
    END IF;

    IF INSERTING THEN
        INSERT INTO Audit_Log (username, action_type)
        VALUES (USER, 'INSERT');
    ELSIF UPDATING THEN
        INSERT INTO Audit_Log (username, action_type)
        VALUES (USER, 'UPDATE');
    ELSIF DELETING THEN
        INSERT INTO Audit_Log (username, action_type)
        VALUES (USER, 'DELETE');
    END IF;
END;
